const PERSONALITY_MODIFIERS = ['', 'とても', 'やや', '根っからの', '隠れ'];

// カテゴリ×基礎語彙×強度接頭辞を掛け合わせて約2,000件の性格データベースを構築する
const PERSONALITY_DATABASE = (function build() {
  const seen = new Set();
  const list = [];
  for (const category in PERSONALITY_CATEGORIES) {
    for (const base of PERSONALITY_CATEGORIES[category]) {
      for (const mod of PERSONALITY_MODIFIERS) {
        const text = mod ? mod + base : base;
        if (seen.has(text)) continue;
        seen.add(text);
        list.push({ text, category, base });
      }
    }
  }
  return list;
})();

// 誕生時の先天性性格を1〜3個、重複なく抽出する
function pickInnateTraits() {
  const count = 1 + Math.floor(Math.random() * 3);
  const pool = PERSONALITY_DATABASE.slice();
  const result = [];
  for (let i = 0; i < count && pool.length > 0; i++) {
    const idx = Math.floor(Math.random() * pool.length);
    result.push(pool.splice(idx, 1)[0].text);
  }
  return result;
}

// 体験コンテキスト(カテゴリ名)に寄せて後天性性格を1つ抽出する。excludeSetは既に持つタグ。
function pickPersonalityFromCategory(category, excludeSet) {
  excludeSet = excludeSet || new Set();
  const candidates = PERSONALITY_DATABASE.filter((p) => (!category || p.category === category) && !excludeSet.has(p.text));
  if (candidates.length === 0) return null;
  return candidates[Math.floor(Math.random() * candidates.length)].text;
}
